// Copy the single-file build to the repo root so Owner can open index.html by double-click,
// and lock it down with a Content Security Policy: only this page's own script may run, and it may only
// connect to the four AI providers. Nothing else can be loaded or sent anywhere.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const built = path.join(here, '..', 'dist', 'index.html'),
  target = path.join(here, '..', '..', 'index.html');
let html = fs.readFileSync(built, 'utf8');
if (/<script[^>]+src=|<link[^>]+href="(?!data:)[^"]+\.css"/.test(html)) throw new Error('build is not self-contained');
const scripts = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]);
if (!scripts.length) throw new Error('no inline script found');
const risky = scripts.join('\n').match(/\beval\s*\(|new Function\s*\(/g);
if (risky) console.warn('warning: the bundle uses', [...new Set(risky)].join(', '), '- the policy blocks it');
const hashes = scripts.map(s => `'sha256-${crypto.createHash('sha256').update(s, 'utf8').digest('base64')}'`);
const csp = [
  "default-src 'none'",
  `script-src ${hashes.join(' ')}`,
  "style-src 'unsafe-inline'",
  'img-src data: blob:',
  'font-src data:',
  'connect-src https://api.anthropic.com https://api.openai.com https://api.x.ai https://generativelanguage.googleapis.com https://iihjcqiiavleyheqzotl.supabase.co https://api.groq.com https://api.cerebras.ai https://api.meta.ai https://api.github.com https://raw.githubusercontent.com',
  "base-uri 'none'",
  "form-action 'none'",
  "object-src 'none'",
  "worker-src 'none'",
  "manifest-src 'none'",
  "media-src 'none'",
  "frame-src 'none'",
].join('; ');
if (!/<head>/.test(html)) throw new Error('no <head> to put the policy in');
html = html.replace('<head>', `<head>\n<meta http-equiv="Content-Security-Policy" content="${csp}">`);
const banner = '<!-- Built from app/ by `npm run build`. Do not edit this file; edit app/src instead. -->\n';
fs.writeFileSync(target, banner + html);
console.log(
  'wrote',
  path.relative(process.cwd(), target),
  (html.length / 1024).toFixed(0) + ' KB;',
  scripts.length,
  'script(s) pinned by hash',
);
